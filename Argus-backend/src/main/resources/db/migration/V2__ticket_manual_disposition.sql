-- v2 工单人工处置：执行记录核验 + 重试授权额度 + 处置审计表
-- 说明：不修改任何现有表结构与既有列，仅在 ticket_executions / tickets 上新增列，并新建 ticket_dispositions 审计表；
--       存量执行记录 verification_status 保持 NULL（未核验），存量工单 extra_attempts 保持 0。
--       核验结论与执行器原始结论分离：result 仍保存执行器输出（SUCCESS/FAILED/UNCERTAIN），
--       verification_status 单独记录人工核验结论（CONFIRMED_SUCCESS / CONFIRMED_NOT_EXECUTED）。

-- ① 执行记录新增人工核验结论（NULL = 尚未核验）
ALTER TABLE ticket_executions
    ADD COLUMN verification_status VARCHAR(32) NULL,   -- ExecutionVerification.name()，NULL=未核验
    ADD COLUMN verified_by        BIGINT       NULL,   -- 核验操作人（无 FK：users 表不在 Flyway 管理范围）
    ADD COLUMN verified_at        TIMESTAMP    NULL;   -- 核验时间

-- ② 工单新增受控重试授权额度（仅能由人工处置递增，创建时默认 0）
ALTER TABLE tickets
    ADD COLUMN extra_attempts INT NOT NULL DEFAULT 0;

-- ③ 人工处置审计表（不可变追加：谁、何时、做了什么、原因、处置前后状态）
CREATE TABLE ticket_dispositions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id        BIGINT       NOT NULL REFERENCES tickets(id),
    execution_id     BIGINT       NULL REFERENCES ticket_executions(id),  -- CONFIRM_* 指向被核验记录，其余为 NULL
    disposition_type VARCHAR(32)  NOT NULL,                               -- DispositionType.name()
    reason           TEXT         NOT NULL,                               -- 处置原因（必填）
    operator_user_id BIGINT       NOT NULL,                               -- 操作人（无 FK：users 表不在 Flyway 管理范围）
    from_status      VARCHAR(32)  NOT NULL,                               -- 处置前工单状态
    to_status        VARCHAR(32)  NOT NULL,                               -- 处置后工单状态
    created_at       TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_ticket_dispositions_ticket    ON ticket_dispositions(ticket_id);
CREATE INDEX idx_ticket_dispositions_execution ON ticket_dispositions(execution_id);
