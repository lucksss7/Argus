-- v1 智能工单模块：三张业务表
-- 说明：不修改任何现有表；执行记录每次尝试独立一行；审批结果与执行结果分离。

-- ① 工单
CREATE TABLE tickets (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_no        VARCHAR(64)  NOT NULL UNIQUE,        -- 工单号
    title            VARCHAR(200) NOT NULL,
    description      TEXT,                                -- 申请原因等描述
    type             VARCHAR(32)  NOT NULL,               -- 工单类型，如 ACCOUNT_PROVISIONING
    status           VARCHAR(32)  NOT NULL,               -- 状态，TicketStatus.name()
    priority         VARCHAR(16),
    creator_user_id  BIGINT       NOT NULL,               -- 创建人（来自登录态，不信任 Agent 传入）
    assignee_user_id BIGINT,                              -- 处理人，NULL=未分配
    approver_user_id BIGINT,                              -- 审批人，NULL=待定
    system_name      VARCHAR(100) NOT NULL,               -- 目标系统
    target_username  VARCHAR(100) NOT NULL,               -- 要开通账号的目标用户
    permission_level VARCHAR(32)  NOT NULL,               -- READ_ONLY / STANDARD / ADMIN
    resolution       TEXT,
    version          INT          NOT NULL DEFAULT 0,     -- 乐观锁版本号
    idempotency_key  VARCHAR(128) NOT NULL UNIQUE,        -- 建单幂等键（全局唯一）
    created_at       TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at       TIMESTAMP    NOT NULL DEFAULT now()
);

-- ② 执行记录：每次执行尝试独立一行，绝不覆盖失败记录
CREATE TABLE ticket_executions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id        BIGINT       NOT NULL REFERENCES tickets(id),
    execution_type   VARCHAR(32)  NOT NULL,               -- 如 PROVISION_ACCOUNT
    result           VARCHAR(32)  NOT NULL,               -- PENDING / SUCCESS / FAILED
    error_message    TEXT,
    request_payload  TEXT,                                -- JSON，敏感信息需脱敏
    response_payload TEXT,
    attempt_no       INT          NOT NULL,               -- 第几次尝试（从 1 起）
    idempotency_key  VARCHAR(128) NOT NULL,               -- 业务操作幂等键（可多行）
    operator_user_id BIGINT,                              -- 触发执行的人
    started_at       TIMESTAMP,
    finished_at      TIMESTAMP,
    created_at       TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at       TIMESTAMP    NOT NULL DEFAULT now(),
    -- 同一业务操作的每次尝试唯一（而非 idempotency_key 全局唯一，否则无法记录多次重试）
    CONSTRAINT uk_ticket_execution_attempt UNIQUE (idempotency_key, attempt_no)
);
CREATE INDEX idx_ticket_executions_ticket ON ticket_executions(ticket_id);

-- ③ 审批记录（审计：谁、何时、批了什么）
CREATE TABLE approval_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id        BIGINT       NOT NULL REFERENCES tickets(id),
    approver_user_id BIGINT       NOT NULL,
    result           VARCHAR(32)  NOT NULL,               -- PENDING / APPROVED / REJECTED
    comment          TEXT,                                -- 审批意见
    decided_at       TIMESTAMP,
    created_at       TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at       TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_approval_requests_ticket ON approval_requests(ticket_id);
